import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await mkdir('../.runtime/screenshots',{recursive:true});
await page.goto('http://127.0.0.1:3000/kk');
await page.getByRole('heading',{name:'Бизнесіңіз. Бір қадам алда.'}).waitFor();
await page.locator('.hero-store-scene canvas').waitFor();
await page.screenshot({path:'../.runtime/screenshots/landing.png',fullPage:true});
await page.request.post('http://127.0.0.1:3000/api/v1/auth/demo');
await page.goto('http://127.0.0.1:3000/ru/dashboard');
await page.getByRole('heading',{name:'Ваш бизнес. В полной картине.'}).waitFor();
await page.locator('.mini-scene canvas').waitFor();
await page.screenshot({path:'../.runtime/screenshots/dashboard.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000/kk/dashboard');
await page.getByRole('heading',{name:'Бизнесіңіз. Толық көріністе.'}).waitFor();
await page.screenshot({path:'../.runtime/screenshots/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await writeFile('../.runtime/browser-verification.json',JSON.stringify({errors,mobileOverflow:overflow},null,2));
console.log(JSON.stringify({errors,mobileOverflow:overflow}));
await browser.close();
